"""Run jobs/<job>/main.py on a Kaggle GPU and download its outputs.

Used by .github/workflows/run_job.yml. The job's code (src/ + jobs/<job>/) is zipped and
embedded in a single-file Kaggle script, so nothing private needs to be uploaded elsewhere.
Credentials: KAGGLE_USERNAME + KAGGLE_KEY (legacy key) or a new-style token in KAGGLE_KEY.

  python tools/kaggle_run.py --job smoke --out results/kaggle/smoke/123
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import os
import sys
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

BOOTSTRAP = '''# Auto-generated by tools/kaggle_run.py - do not edit.
import base64, io, os, runpy, sys, zipfile
PAYLOAD = "{payload}"
CODE = "/kaggle/temp_code"
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(CODE)
os.environ["JOB_OUT"] = "/kaggle/working"
os.environ["JOB_NAME"] = "{job}"
sys.path.insert(0, os.path.join(CODE, "src"))
os.chdir(CODE)
runpy.run_path(os.path.join(CODE, "jobs", "{job}", "main.py"), run_name="__main__")
'''


def build_payload(job: str) -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for base in (ROOT / "src", ROOT / "jobs" / job):
            for p in base.rglob("*"):
                if p.is_file() and "__pycache__" not in p.parts:
                    z.write(p, p.relative_to(ROOT))
    data = buf.getvalue()
    if len(data) > 5_000_000:
        raise SystemExit(f"payload too large ({len(data)} bytes); move data to a Kaggle dataset")
    return base64.b64encode(data).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--job", required=True)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--accelerator", default="NvidiaTeslaT4")
    ap.add_argument("--max-hours", type=float, default=5.5)
    a = ap.parse_args()

    key = os.environ.get("KAGGLE_KEY", "")
    if key.startswith("KGAT_") and not os.environ.get("KAGGLE_API_TOKEN"):
        os.environ["KAGGLE_API_TOKEN"] = key          # new-style token stored under KAGGLE_KEY
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    user = os.environ.get("KAGGLE_USERNAME") or api.config_values.get("username")
    if not user:
        raise SystemExit("Could not determine the Kaggle username; set the KAGGLE_USERNAME secret.")

    try:  # weekly GPU quota; 0 or an error usually means the Kaggle account is not phone-verified
        q = api.quota_view()
        print("accelerator quota:", q, flush=True)
    except Exception as e:
        q = f"unavailable: {e}"
        print("accelerator quota", q, flush=True)
    slug = f"eegpp-{a.job}".lower().replace("_", "-")
    kdir = ROOT / "build" / "kernel" / a.job
    kdir.mkdir(parents=True, exist_ok=True)
    (kdir / "run.py").write_text(BOOTSTRAP.format(payload=build_payload(a.job), job=a.job))
    meta = dict(id=f"{user}/{slug}", title=slug, code_file="run.py", language="python",
                kernel_type="script", is_private=True, enable_gpu=True, enable_tpu=False,
                enable_internet=True, dataset_sources=[], competition_sources=[],
                kernel_sources=[], model_sources=[])
    (kdir / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))

    a.out.mkdir(parents=True, exist_ok=True)
    status = dict(job=a.job, kernel=meta["id"], accelerator=a.accelerator, started=time.time(), quota=str(q))
    try:
        resp = api.kernels_push(str(kdir), timeout=str(int(a.max_hours * 3600)), acc=a.accelerator)
    except Exception as e:   # unknown accelerator name etc. -> retry with the default GPU
        print(f"push with accelerator {a.accelerator} failed ({e}); retrying with default GPU", flush=True)
        status["accelerator"] = "default"
        resp = api.kernels_push(str(kdir), timeout=str(int(a.max_hours * 3600)), acc=None)
    err = getattr(resp, "error", None)
    if err:
        status.update(state="push_error", error=str(err))
        (a.out / "status.json").write_text(json.dumps(status, indent=1))
        raise SystemExit(f"push error: {err}")
    print(f"pushed {meta['id']} version {getattr(resp, 'version_number', '?')}: {getattr(resp, 'url', '')}", flush=True)

    deadline = time.time() + a.max_hours * 3600 + 900
    state, last = "unknown", None
    time.sleep(30)
    while time.time() < deadline:
        try:
            s = api.kernels_status(meta["id"])
            state = str(getattr(s, "status", s)).split(".")[-1].lower()
            fail = getattr(s, "failure_message", "") or ""
        except Exception as e:  # transient API errors
            state, fail = "status_error", str(e)
        if state != last:
            print(f"[{time.strftime('%H:%M:%S')}] {state} {fail}", flush=True)
            last = state
        if state in ("complete", "error", "cancel_acknowledged", "cancelacknowledged"):
            break
        time.sleep(60)
    status.update(state=state, finished=time.time(), minutes=(time.time() - status["started"]) / 60)
    try:
        api.kernels_output(meta["id"], path=str(a.out), force=True, quiet=True)
    except Exception as e:
        status["output_error"] = str(e)
    (a.out / "status.json").write_text(json.dumps(status, indent=1))
    print(json.dumps(status, indent=1), flush=True)
    sys.exit(0 if state == "complete" else 1)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:  # record early failures (auth, push) so they reach the results commit
        import traceback
        args = sys.argv
        out = Path(args[args.index("--out") + 1]) if "--out" in args else ROOT / "results" / "kaggle" / "error"
        out.mkdir(parents=True, exist_ok=True)
        tb = traceback.format_exc()
        for secret in (os.environ.get("KAGGLE_KEY"), os.environ.get("KAGGLE_API_TOKEN")):
            if secret:
                tb = tb.replace(secret, "***")
        (out / "status.json").write_text(json.dumps(dict(state="runner_error", error=tb), indent=1))
        print(tb, flush=True)
        sys.exit(1)
